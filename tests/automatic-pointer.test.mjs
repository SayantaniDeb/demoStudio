import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code = ts.transpileModule(fs.readFileSync('src/automaticPointer.ts','utf8'), {compilerOptions:{module:ts.ModuleKind.ES2022,target:ts.ScriptTarget.ES2022}}).outputText;
const {automaticPointer} = await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const samples=[{time:1,click:false},{time:2,click:true},{time:4,click:true}];
assert.equal(automaticPointer(samples,1),'arrow');
assert.equal(automaticPointer(samples,1.95),'hand');
assert.equal(automaticPointer(samples,2.2),'hand');
assert.equal(automaticPointer(samples,2.5),'arrow');
assert.equal(automaticPointer(samples,4.1),'hand');
assert.equal(automaticPointer(samples,1),'arrow');
assert.equal(automaticPointer([],2),'arrow');
console.log('Passed: automatic click states, return to arrow, deterministic backward seeking, and missing telemetry');
const shapes=[{time:0,click:false,shape:'arrow'},{time:1,click:false,shape:'hand'},{time:2,click:true,shape:'ibeam'},{time:3,click:false,shape:'arrow'}];
assert.equal(automaticPointer(shapes,1.2),'hand');
assert.equal(automaticPointer(shapes,2.1),'ibeam');
assert.equal(automaticPointer(shapes,3.1),'arrow');
assert.equal(automaticPointer(shapes,.5),'arrow');
console.log('Passed: recorded hover shapes, text cursor while clicking, and backward seeking');
const {pointerTransition}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.equal(pointerTransition(shapes,.8).mix,1);
const midway=pointerTransition(shapes,1.08);
assert.equal(midway.from,'arrow');assert.equal(midway.to,'hand');assert(Math.abs(midway.mix-.5)<.01);
assert.equal(pointerTransition(shapes,1.3).mix,1);
assert.deepEqual(pointerTransition(shapes,1.08),midway);
console.log('Passed: eased pointer crossfade, settled state, and deterministic seeking');
const {pointerLayers}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const jitter=[{time:0,click:false,shape:'arrow'},{time:1,click:false,shape:'hand'},{time:1.03,click:false,shape:'arrow'},{time:2,click:false,shape:'ibeam'},{time:3,click:false,shape:'ibeam'}];
assert.equal(pointerLayers(jitter,1.2)[0].shape,'arrow');
const layers=pointerLayers(jitter,2.05);assert(layers.length===2);assert(Math.abs(layers.reduce((n,l)=>n+l.opacity,0)-1)<1e-10);
assert.equal(pointerLayers(jitter,2.8)[0].shape,'ibeam');
assert.deepEqual(pointerLayers(jitter,2.05),layers);
console.log('Passed: transient hover suppression, normalized multi-shape blending, settled text state, and repeatable seeking');
const textChange=[{time:0,click:false,shape:'arrow'},{time:1,click:false,shape:'ibeam'},{time:2,click:false,shape:'ibeam'}];
const textWeight=t=>pointerLayers(textChange,t).find(l=>l.shape==='ibeam')?.opacity||0;
assert(Math.abs(textWeight(1)-.5)<.00001,'Text transition must be centered on the actual hover change');
for(let t=.87;t<1.13;t+=.001)assert(Math.abs(textWeight(t+.001)-textWeight(t))<.006,'Every millisecond must blend continuously');
assert.equal(textWeight(1.2),1);
console.log('Passed: no I-beam delay, exact continuous blending at fine time steps, and settled text state');
