import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';
const code = ts.transpileModule(fs.readFileSync('src/screenTrims.ts', 'utf8'), {compilerOptions: {module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022}}).outputText;
const {screenRange, trimScreenEdge, screenOpacity} = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
const original = {id: 'first', start: 0, end: 10};
const trimmed = trimScreenEdge(trimScreenEdge(original, 'start', 2), 'end', 8);
assert.equal(trimmed.start, 0); assert.equal(trimmed.end, 10);
assert.deepEqual(screenRange(trimmed), {start: 2, end: 8});
assert.equal(screenOpacity(trimmed, 1), 0); assert.equal(screenOpacity(trimmed, 9), 0);
assert.equal(screenOpacity(trimmed, 5), 1);
assert(screenOpacity(trimmed, 2.1) > 0 && screenOpacity(trimmed, 2.1) < 1);
assert(screenOpacity(trimmed, 7.9) > 0 && screenOpacity(trimmed, 7.9) < 1);
assert.deepEqual(screenRange(trimScreenEdge(trimmed, 'start', -100)), {start: 0, end: 8});
assert.equal(screenRange(trimScreenEdge(trimmed, 'end', 100)).end, 10);
assert(screenRange(trimScreenEdge(trimmed, 'start', 20)).end - screenRange(trimScreenEdge(trimmed, 'start', 20)).start >= 0.25);
const next = {id: 'second', start: 10, end: 20};
assert.equal((trimmed.end - trimmed.start) + (next.end - next.start), 20, 'Trimming must not move later clips or shorten the project');
console.log('Passed: screen trims leave blank time, preserve later clip timing, restore hidden content, and ease in/out');
assert.equal(screenOpacity({...original,hidden:true},5),0,'Hidden footage should not render');
assert.deepEqual(screenRange({...original,hidden:true}),screenRange(original),'Hide preserves duration and source timing');
assert.equal(screenOpacity({...original,hidden:false},5),1,'Show restores footage');
const {cameraSoloMix}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert(cameraSoloMix([{...original,hidden:true}],5,true)>.99,'Hidden screen allows camera-only layout');
assert(cameraSoloMix([original],5,true)<.01,'Visible screen restores overlay layout');
